//! 原生卡片渲染层：不经浏览器，把结构化内容直接光栅化成 PNG。
//!
//! 三层职责，从下往上：
//!   - [`font`] —— 字体装载与逐字符回退链；
//!   - [`canvas`] —— 逻辑像素画布：几何图元、文字度量与绘制、折行；
//!   - [`kit`] —— 「系统类卡片」的成品部件（外壳、页眉、分区、条目、页脚），
//!     由 [`kit::Theme`] 决定配色，help 与 ctl 共用同一套版式语言。
//!
//! 插件按需要选层次：版式独特的（词意的宣纸卡）只取 canvas 自己画；
//! 版式规整的（帮助、控制台）直接用 kit，新增一张卡通常只是列几行数据。
//!
//! 出图失败（环境里没有任何可用字体）时各插件一律退回纯文本，功能不受影响。

// 渲染层是一套「画卡片用的工具箱」，成套提供才好用：`hgrad` 有 `vgrad`、
// 宋黑两族各有常规与加粗、Block 里留着 `Gap`。某一件暂时没人调用不代表它多余，
// 下一张卡片就可能要它，所以这里不按调用数裁剪 API。
#![allow(dead_code)]

pub mod canvas;
pub mod font;
pub mod kit;

pub use canvas::{Canvas, Ink};
pub use font::Fonts;
